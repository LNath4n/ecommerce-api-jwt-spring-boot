package com.ecommerce.FerreViky.service;

import com.ecommerce.FerreViky.utils.EmailLanguage;
import jakarta.mail.MessagingException;
import jakarta.mail.internet.MimeMessage;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.mail.javamail.JavaMailSender;
import org.springframework.mail.javamail.MimeMessageHelper;
import org.springframework.stereotype.Service;

import java.nio.charset.StandardCharsets;

/**
 * Service responsible for sending transactional emails to customers.
 *
 * <p>Currently it supports the account verification email, which is
 * rendered as an HTML message and localized in Spanish or English
 * according to the customer's preferred {@link EmailLanguage}.</p>
 *
 * <p>Email delivery is treated as a non-critical side effect: failures
 * are logged but never propagated, so they do not interrupt the
 * operation that triggered the email (for example, a sign-up).</p>
 */
@Service
public class EmailService {

    private static final Logger log = LoggerFactory.getLogger(EmailService.class);

    /**
     * Spring mail sender used to build and deliver MIME messages.
     */
    private final JavaMailSender mailSender;

    /**
     * Sender address shown in the {@code From} header of every email.
     * Configured through the {@code app.mail.from} property.
     */
    private final String from;

    /**
     * Base URL of the frontend application, used to build the links
     * included in emails. Configured through the
     * {@code app.frontend.base-url} property.
     */
    private final String frontendBaseUrl;

    /**
     * Creates the service with its mail configuration.
     *
     * @param mailSender      Spring component used to send the emails
     * @param from            sender address, from {@code app.mail.from}
     * @param frontendBaseUrl frontend base URL, from {@code app.frontend.base-url}
     */
    public EmailService(
            JavaMailSender mailSender,
            @Value("${app.mail.from}") String from,
            @Value("${app.frontend.base-url}") String frontendBaseUrl) {
        this.mailSender = mailSender;
        this.from = from;
        this.frontendBaseUrl = frontendBaseUrl;
    }

    /**
     * Sends the email verification link to a newly registered customer.
     *
     * <p>The link has the form
     * {@code <frontendBaseUrl>/verify-email?token=<rawToken>}. The subject
     * and body are localized according to {@code language}: Spanish for
     * {@link EmailLanguage#ES}, English for any other value.</p>
     *
     * <p>The body is an HTML message with a call-to-action button and a
     * plain-text fallback link for email clients that do not render the
     * button correctly.</p>
     *
     * <p>Failures are logged but not thrown: the account is already saved
     * and the user can request a new email through the resend endpoint.
     * The recipient address is intentionally not logged.</p>
     *
     * @param to       recipient email address
     * @param rawToken verification token in plain text, as generated by
     *                 {@link VerificationTokenService#create(Long)}
     * @param language language in which the email is written
     */
    public void sendVerificationEmail(String to, String rawToken, EmailLanguage language) {
        String link = frontendBaseUrl + "/verify-email?token=" + rawToken;

        // Localized texts: Spanish for ES, English otherwise.
        boolean es = language == EmailLanguage.ES;
        String subject = es ? "Verifica tu correo - Ecommerce" : "Verify your email - Ecommerce";
        String title   = es ? "Verifica tu correo" : "Verify your email";
        String intro   = es
                ? "Gracias por registrarte en Ecommerce. Confirma tu correo para activar tu cuenta:"
                : "Thanks for signing up at Ecommerce. Confirm your email to activate your account:";
        String button  = es ? "Verificar correo" : "Verify email";
        String fallback = es
                ? "Si el botón no funciona, copia y pega este enlace en tu navegador:"
                : "If the button doesn't work, copy and paste this link into your browser:";
        String footer  = es
                ? "El enlace vence en 24 horas. Si no creaste esta cuenta, ignora este mensaje."
                : "This link expires in 24 hours. If you didn't create this account, ignore this message.";

        // HTML template. Placeholders (in order): title, intro, link, button,
        // fallback, link, link, footer. A literal percent sign must be written as %%.
        String html = """
            <table role="presentation" width="100%%" cellpadding="0" cellspacing="0"
                   style="background:#eff1f0;padding:32px 16px;font-family:Inter,Arial,sans-serif;">
              <tr>
                <td align="center">
                  <table role="presentation" width="480" cellpadding="0" cellspacing="0"
                         style="max-width:480px;background:#ffffff;border-radius:16px;overflow:hidden;">
                    <tr>
                      <td style="background:#3b5d50;padding:24px 32px;">
                        <span style="color:#ffffff;font-size:26px;font-weight:700;">
                          Ecommerce<span style="color:#f9bf29;">.</span>
                        </span>
                      </td>
                    </tr>
                    <tr>
                      <td style="padding:32px;color:#2f2f2f;">
                        <h2 style="margin:0 0 12px;font-size:22px;color:#2f2f2f;">%s</h2>
                        <p style="margin:0 0 24px;font-size:15px;line-height:1.5;color:#6a6a6a;">%s</p>
                        <p style="margin:0 0 24px;text-align:center;">
                          <a href="%s"
                             style="background:#3b5d50;color:#ffffff;padding:14px 32px;
                                    text-decoration:none;border-radius:50px;font-weight:600;
                                    font-size:15px;display:inline-block;">
                            %s
                          </a>
                        </p>
                        <p style="margin:0 0 4px;font-size:12px;color:#6a6a6a;">%s</p>
                        <p style="margin:0 0 24px;font-size:12px;word-break:break-all;">
                          <a href="%s" style="color:#3b5d50;">%s</a>
                        </p>
                        <p style="margin:0;font-size:13px;color:#6a6a6a;border-top:1px solid #eff1f0;padding-top:16px;">%s</p>
                      </td>
                    </tr>
                  </table>
                </td>
              </tr>
            </table>
            """.formatted(title, intro, link, button, fallback, link, link, footer);

        try {
            MimeMessage message = mailSender.createMimeMessage();
            MimeMessageHelper helper = new MimeMessageHelper(message, StandardCharsets.UTF_8.name());
            helper.setFrom(from);
            helper.setTo(to);
            helper.setSubject(subject);
            helper.setText(html, true);
            mailSender.send(message);
            log.info("Verification email sent");
        } catch (MessagingException | RuntimeException e) {
            log.error("Verification email could not be sent", e);
        }
    }
}